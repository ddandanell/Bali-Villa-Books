/** Every marketing route is real initial HTML. Rendering failures fail the release. */
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const output = path.join(root, "dist/public");
const server = path.join(root, "dist/server");
const { render, pageDocument, sitePages, staticJournalPosts } = await import(path.join(server, "entry-server.js"));
const template = readFileSync(path.join(output, "index.html"), "utf8");
const pages = Object.keys(sitePages);
const imagery = JSON.parse(readFileSync(path.join(root, "../../lib/site-content/src/page-imagery.json"), "utf8"));
if (JSON.stringify([...pages, "/blog"].sort()) !== JSON.stringify(Object.keys(imagery).sort()))
  throw new Error("Canonical page routes and the imagery/sitemap inventory have drifted.");
for (const [pathname, visual] of Object.entries(imagery)) {
  for (const asset of [visual.imageUrl, visual.shareImage]) {
    if (!asset.startsWith("/images/") || !readFileSync(path.join(output, asset.slice(1))).length)
      throw new Error(`Missing image for ${pathname}: ${asset}`);
  }
}
for (const pathname of [...pages, "/404"]) {
  const target = pathname === "/" ? path.join(output, "index.html") : path.join(output, pathname.slice(1), "index.html");
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, pageDocument(template, render(pathname), pathname));
}
// Journal articles served from this build rather than the Replit database.
// dist/public files win over vercel.json rewrites, so /blog/<slug> resolves here.
const journalPaths = [];
for (const post of staticJournalPosts) {
  const pathname = `/blog/${post.slug}`;
  const target = path.join(output, "blog", post.slug, "index.html");
  mkdirSync(path.dirname(target), { recursive: true });
  const html = pageDocument(template, render(pathname, post), pathname, {
    title: post.metaTitle, description: post.metaDescription, category: post.category,
    publishedAt: post.publishedAt, updatedAt: post.updatedAt,
    imageUrl: post.imageUrl, imageAlt: post.imageAlt, faqs: post.faqs,
  });
  const bootstrap = JSON.stringify({ post, static: true }).replace(/</g, "\\u003c");
  writeFileSync(target, html.replace("</head>", `<script>window.__BLOG_INITIAL__=${bootstrap}</script></head>`));
  journalPaths.push(pathname);
}
writeFileSync(path.join(output, "journal-static.json"), JSON.stringify(journalPaths));
writeFileSync(path.join(output, "routes.json"), JSON.stringify(pages));
// Marketing routes are fixed in this build, so their sitemap is generated here.
// The journal origin keeps its own sitemap; neither list has to know the other.
{
  const today = new Date().toISOString().slice(0, 10);
  const entries = pages.map(route => {
    const priority = route === "/" ? "1.0" : /^\/(pricing|services|compare)$/.test(route) ? "0.9" : route.startsWith("/compare/") ? "0.8" : "0.7";
    return `  <url><loc>https://bali-villa-accounting-service.com${route === "/" ? "/" : route}</loc><lastmod>${today}</lastmod><changefreq>monthly</changefreq><priority>${priority}</priority></url>`;
  }).join("\n");
  writeFileSync(path.join(output, "sitemap-pages.xml"),
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`);
  process.stdout.write(`Wrote sitemap-pages.xml with ${pages.length} URL(s).\n`);
}
// Vercel serves this document with a real 404 instead of a homepage fallback.
writeFileSync(path.join(output, "404.html"), pageDocument(template, render("/404"), "/404"));
// The main sitemap is generated by the journal origin; this one covers only the
// articles this build renders, so neither list has to know about the other.
if (journalPaths.length) {
  const entries = staticJournalPosts.map(post =>
    `  <url><loc>https://bali-villa-accounting-service.com/blog/${post.slug}</loc><lastmod>${post.updatedAt.slice(0, 10)}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>`
  ).join("\n");
  writeFileSync(path.join(output, "sitemap-journal.xml"),
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`);
  process.stdout.write(`Wrote sitemap-journal.xml with ${journalPaths.length} URL(s).\n`);
}
writeFileSync(path.join(output, "robots.txt"), "User-agent: *\nAllow: /\nDisallow: /api/\nSitemap: https://bali-villa-accounting-service.com/sitemap.xml\nSitemap: https://bali-villa-accounting-service.com/sitemap-journal.xml\nSitemap: https://bali-villa-accounting-service.com/sitemap-pages.xml\n");
// The Replit origin builds the journal documents, and its build is older than
// this one: it references /assets/index-<hash>.js and .css that no longer exist
// here, so every proxied journal URL asked for a stylesheet and a bundle that
// both 404. Publish this build's real pair at stable aliases and let the gateway
// repoint the origin's references at them. The origin markup is kept as-is; only
// the two asset URLs change. Remove this once the origin is rebuilt from the same
// commit or the journal is served entirely from this build.
{
  const shell = readFileSync(path.join(output, "index.html"), "utf8");
  const js = shell.match(/assets\/index-[A-Za-z0-9_.-]+\.js/);
  const css = shell.match(/assets\/index-[A-Za-z0-9_.-]+\.css/);
  if (!js || !css) throw new Error("Shell asset hashes not found; journal asset aliases cannot be written.");
  copyFileSync(path.join(output, js[0]), path.join(output, "assets/app.js"));
  copyFileSync(path.join(output, css[0]), path.join(output, "assets/app.css"));
  writeFileSync(path.join(output, "journal-assets.json"),
    JSON.stringify({ from: { js: js[0], css: css[0] }, alias: { js: "/assets/app.js", css: "/assets/app.css" } }, null, 2) + "\n");
  process.stdout.write(`Journal asset aliases: ${js[0]} -> /assets/app.js, ${css[0]} -> /assets/app.css.\n`);
}
rmSync(server, { recursive: true, force: true });
process.stdout.write(`Pre-rendered ${pages.length} marketing pages, ${journalPaths.length} static journal article(s) and a real 404 document.\n`);
