/**
 * Generates api/journal-art.mjs from lib/site-content/src/journal-imagery.json.
 * The gateway is a plain ESM function bundle, so it takes a committed copy of
 * the art map rather than importing the TypeScript workspace at runtime.
 * Run: node scripts/src/build-journal-art.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const source = path.join(root, "lib/site-content/src/journal-imagery.json");
const target = path.join(root, "api/journal-art.mjs");

const imagery = JSON.parse(readFileSync(source, "utf8"));
const entries = Object.entries(imagery)
  .filter(([, art]) => art.imageUrl?.startsWith("/images/journal/") && art.shareImage?.startsWith("/images/share/"))
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, art]) => [slug, { imageUrl: art.imageUrl, shareImage: art.shareImage, imageAlt: art.imageAlt, caption: art.caption ?? "" }]);

const body = `/**
 * Generated by scripts/src/build-journal-art.mjs from lib/site-content/src/journal-imagery.json.
 * Do not edit by hand; rerun the generator. scripts/src/test-journal-art.mjs fails if this drifts.
 *
 * Why it exists: the journal documents for the 75 proxied articles are rendered
 * by the Replit origin, whose build predates this art. The gateway uses this map
 * to serve the local hero, share card and schema image until that origin is
 * redeployed. Once it is, the origin emits these paths itself and every
 * replacement below becomes a no-op.
 */
export const journalArt = ${JSON.stringify(Object.fromEntries(entries), null, 2)};
`;
writeFileSync(target, body);
process.stdout.write(`Wrote api/journal-art.mjs with ${entries.length} article(s).\n`);
