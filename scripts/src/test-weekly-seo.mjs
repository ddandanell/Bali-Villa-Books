import assert from "node:assert/strict";
import { internalUrl, inspectHtml, audit } from "./weekly-seo.mjs";
import { includeArticleService } from "../../api/gateway.mjs";
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const origin = "https://bali-villa-accounting-service.com";
assert.equal(internalUrl("https://other.example/private"), null);
assert.equal(internalUrl("/api/blog/posts"), null);
assert.equal(internalUrl("/blog?page=2&email=private#secret"), origin + "/blog?page=2");
assert.equal(internalUrl("/pricing?name=private"), origin + "/pricing");
const html = (path, extra = "") => `<html><head><title>${path}</title><meta content='Description of ${path}' name='description'><link href='${origin}${path}' rel='canonical'></head><body><main><h1>Page</h1>${extra}</main></body></html>`;
assert.deepEqual(inspectHtml(html("/"), origin + "/").issues, []);
assert.ok(inspectHtml("<h1>x</h1>", origin + "/").issues.includes("Expected one nonempty meta description"));
assert.ok(inspectHtml(html("/", '<a href="/pricing">Click here</a>'), origin + "/").issues.some(i => i.includes("Generic anchor")));
const report = await audit(async url => {
  if (url.includes("sitemap")) return new Response(`<urlset><url><loc>${origin}/</loc></url><url><loc>${origin}/pricing</loc></url></urlset>`, { headers: { "content-type": "application/xml" } });
  const path = new URL(url).pathname;
  return new Response(html(path, path === "/" ? '<a href="/pricing">Bookkeeping prices</a><a href="/blog">Guides</a>' : '<a href="/">Home</a>'), { headers: { "content-type": "text/html" } });
});
assert.equal(report.incomplete, false);
assert.equal(report.pages.length, 3);
assert.ok(report.pages.every(p => !p.issues.length));
assert.equal(report.analytics.status, "unavailable");
const failed = await audit(async () => { throw new Error("offline"); });
assert.equal(failed.incomplete, true);
assert.ok(failed.failures.length);
const locked = "airbnb-bookkeeping-refunds-cancellations-reserves";
const linked = includeArticleService("<main><h1>Article</h1></main>", locked);
assert.ok(linked.includes('href="/airbnb-ota-reconciliation-bali"'));
assert.equal(includeArticleService(linked, locked), linked);
assert.equal(includeArticleService("<main></main>", "unknown"), "<main></main>");
const dir = mkdtempSync(join(tmpdir(), "weekly-seo-"));
try {
  const target = join(dir, "helpers.cjs");
  execFileSync("pnpm", ["--filter", "@workspace/api-server", "exec", "esbuild", "../../artifacts/villabooks-bali/src/lib/measurement-url.ts", "--bundle", "--platform=node", "--format=cjs", `--outfile=${target}`], { stdio: "pipe" });
  const { measurementUrl } = createRequire(import.meta.url)(target);
  assert.equal(measurementUrl(`${origin}/pricing?email=private#secret`), `${origin}/pricing`);
  assert.equal(measurementUrl(`${origin}/private/customer-name`), null);
  assert.equal(measurementUrl("https://other.example/"), null);
  assert.equal(measurementUrl(`${origin}/blog/guide-name`), `${origin}/blog/guide-name`);
} finally { rmSync(dir, { recursive: true, force: true }); }
const document = readFileSync("artifacts/villabooks-bali/src/lib/page-document.ts", "utf8");
assert.ok(!document.includes("openingHoursSpecification"));
const prerender = readFileSync("artifacts/villabooks-bali/prerender.mjs", "utf8");
assert.ok(!prerender.includes("${today}"));
console.log("PASS: weekly inventory, HTML metadata, privacy filtering, partial failures, shared service links and schema/sitemap safeguards.");
